function mediaLoadProfile(
  target: string,
  value: { height: number; width: number },
): ToolcraftPerformanceLoadProfile {
  return {
    hardLimit: value,
    metric: "media-area",
    smoothTarget: value,
    smoothTargetRatio: 1,
    target,
    userFacingRange: "fully-guaranteed",
  };
}

